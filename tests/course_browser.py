"""Real student/teacher course flow; run against a separate development API store."""
import json, os, sys, time
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'work/python-deps'))
from playwright.sync_api import sync_playwright, expect
expect.set_options(timeout=15000)
URL = os.environ.get('COLORVERSE_TEST_URL', 'http://127.0.0.1:5176')
checks, errors = [], []
def passed(message):
    checks.append(message)
    print('PASS:', message, flush=True)
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, channel='chrome' if os.name == 'nt' else None,
        args=['--enable-webgl', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'])
    def classroom(account):
        context = browser.new_context(viewport={'width':1440, 'height':1000}, reduced_motion='reduce')
        page = context.new_page()
        page.on('pageerror', lambda error: errors.append(str(error)))
        page.on('response', lambda response: errors.append(f'HTTP {response.status}: {response.url}') if response.status >= 500 else None)
        page.goto(URL)
        page.wait_for_load_state('networkidle')
        page.get_by_role('button', name='课程作业', exact=True).click()
        page.get_by_role('button', name=account).click()
        expect(page.get_by_role('button', name='退出课堂', exact=True)).to_be_visible()
        return context, page
    tc, teacher = classroom('测试教师 · 色彩老师')
    title = f'浏览器测试作业 {time.time_ns()}'
    teacher.get_by_role('button', name='＋ 布置作业', exact=True).click()
    teacher.get_by_label('新作业名称', exact=True).fill(title)
    teacher.get_by_label('新作业模块', exact=True).fill('冷暖与情绪')
    teacher.get_by_label('新作业要求', exact=True).fill('保留作品及修改版本')
    teacher.get_by_label('新作业截止时间', exact=True).fill('2030-10-10T16:00')
    teacher.get_by_label('新作业补交截止', exact=True).fill('2030-10-11T16:00')
    teacher.get_by_role('button', name='发布作业', exact=True).click()
    expect(teacher.get_by_role('heading', name=title, exact=True)).to_be_visible()
    passed('teacher publishes a class assignment with a Shanghai local deadline')
    sc, student = classroom('测试学生 · 林同学')
    student.locator('.course-assignment-list button').filter(has_text=title).click()
    expect(student.get_by_role('heading', name='我的作业草稿', exact=True)).to_be_visible()
    student.get_by_label('上传作业图片', exact=True).set_input_files(str(ROOT/'tests/fixtures/media/sample-0.png'))
    expect(student.get_by_alt_text('作业图片 1', exact=True)).to_be_visible()
    student.get_by_label('作业创作说明', exact=True).fill('第一版：橙色与蓝色的对话')
    student.get_by_label('作业色彩关键词', exact=True).fill('温暖 对比')
    student.get_by_role('button', name='宇宙展览', exact=True).click()
    expect(student.locator('.course-draft')).to_be_visible()
    expect(student.get_by_text('请先保存作业草稿，并等待当前操作完成，再离开课堂。', exact=True)).to_be_visible()
    passed('unsaved homework blocks navigation instead of silently dropping edits')
    student.get_by_role('button', name='保存作业草稿', exact=True).click()
    expect(student.get_by_text('作业草稿已保存，尚未提交给老师。', exact=True)).to_be_visible()
    teacher.get_by_role('button', name='刷新课堂', exact=True).click()
    expect(teacher.get_by_text('还没有学生提交。私人草稿不会出现在这里。', exact=True)).to_be_visible()
    passed('teacher cannot see private drafts or uploaded draft media in the submission list')
    student.reload()
    student.wait_for_load_state('networkidle')
    student.get_by_role('button', name='课程作业', exact=True).click()
    student.locator('.course-assignment-list button').filter(has_text=title).click()
    expect(student.get_by_label('作业创作说明', exact=True)).to_have_value('第一版：橙色与蓝色的对话')
    expect(student.get_by_label('作业色彩关键词', exact=True)).to_have_value('温暖 对比')
    expect(student.get_by_alt_text('作业图片 1', exact=True)).to_be_visible()
    passed('server session, draft description, color keywords and image survive page reload')
    student.get_by_role('button', name='提交作业', exact=True).click()
    expect(student.get_by_role('status').filter(has_text='提交成功 · 第1版')).to_be_visible()
    expect(student.locator('.course-history')).to_contain_text('第一版：橙色与蓝色的对话')
    first_id = student.get_by_label('选择作业版本', exact=True).input_value()
    passed('student submits an immutable first version and receives a real backend receipt')
    teacher.get_by_role('button', name='刷新课堂', exact=True).click()
    teacher.locator('.course-submissions button').filter(has_text='测试学生 · 林同学').click()
    expect(teacher.locator('.course-history')).to_contain_text('第一版：橙色与蓝色的对话')
    assert teacher.get_by_alt_text('已提交的最终作品', exact=True).evaluate('(image)=>image.complete && image.naturalWidth>0')
    student.get_by_label('作业创作说明', exact=True).fill('仍然私密的下一版草稿')
    student.get_by_role('button', name='保存作业草稿', exact=True).click()
    expect(student.get_by_text('作业草稿已保存，尚未提交给老师。', exact=True)).to_be_visible()
    teacher.get_by_role('button', name='刷新课堂', exact=True).click()
    expect(teacher.locator('.course-history')).to_contain_text('第一版：橙色与蓝色的对话')
    expect(teacher.locator('.course-page')).not_to_contain_text('仍然私密的下一版草稿')
    passed('same-class teacher sees submitted images; later private edits never replace the first version')
    teacher.get_by_label('评阅方式', exact=True).select_option('returned')
    teacher.get_by_label('作业评语', exact=True).fill('请补充过程图并说明冷暖关系')
    teacher.get_by_role('button', name='退回这份作业', exact=True).click()
    expect(teacher.get_by_text('作业已退回，学生可以修改后重新提交。', exact=True)).to_be_visible()
    student.get_by_role('button', name='刷新课堂', exact=True).click()
    expect(student.locator('.course-draft')).to_contain_text('已退回')
    expect(student.locator('.course-history')).to_contain_text('请补充过程图并说明冷暖关系')
    passed('teacher returns a specific version and the student sees the feedback')
    student.get_by_label('上传作业图片', exact=True).set_input_files(str(ROOT/'tests/fixtures/media/sample-1.jpg'))
    expect(student.get_by_alt_text('作业图片 2', exact=True)).to_be_visible()
    student.get_by_label('作业图片 2用途', exact=True).select_option('process')
    student.get_by_label('作业创作说明', exact=True).fill('第二版：补充过程与冷暖关系')
    student.get_by_role('button', name='提交新版本', exact=True).click()
    expect(student.get_by_role('status').filter(has_text='提交成功 · 第2版')).to_be_visible()
    second_id = student.get_by_label('选择作业版本', exact=True).input_value()
    assert first_id != second_id
    student.get_by_label('选择作业版本', exact=True).select_option(first_id)
    expect(student.locator('.course-history')).to_contain_text('第一版：橙色与蓝色的对话')
    expect(student.locator('.course-history img')).to_have_count(1)
    student.get_by_label('选择作业版本', exact=True).select_option(second_id)
    expect(student.locator('.course-history img')).to_have_count(2)
    passed('resubmission creates version two and retains the complete first version')
    teacher.get_by_role('button', name='刷新课堂', exact=True).click()
    expect(teacher.get_by_role('heading', name='评阅第2版', exact=True)).to_be_visible()
    teacher.get_by_label('评阅方式', exact=True).select_option('graded')
    teacher.get_by_label('作业评分', exact=True).fill('88')
    teacher.get_by_label('作业评语', exact=True).fill('对比清晰，继续观察明度层次')
    teacher.get_by_role('button', name='保存评阅', exact=True).click()
    expect(teacher.get_by_text('评阅已保存，学生可以查看分数和评语。', exact=True)).to_be_visible()
    student.get_by_role('button', name='刷新课堂', exact=True).click()
    expect(student.get_by_text('评分 88 / 100', exact=True)).to_be_visible()
    expect(student.get_by_role('button', name='提交新版本', exact=True)).to_be_disabled()
    passed('grading reaches the student and enforces the assignment resubmission policy')
    teacher.screenshot(path=str(ROOT/'outputs/COLORVERSE-course-teacher.png'), full_page=True)
    student.screenshot(path=str(ROOT/'outputs/COLORVERSE-course-student.png'), full_page=True)
    teacher.get_by_label('作业评分', exact=True).fill('90')
    teacher.get_by_label('作业评语', exact=True).fill('更正评分，原记录继续保留')
    teacher.get_by_role('button', name='保存评阅', exact=True).click()
    expect(teacher.get_by_text('评分 90 / 100', exact=True)).to_be_visible()
    expect(teacher.get_by_text('评分 88 / 100', exact=True)).to_be_visible()
    student.get_by_role('button', name='刷新课堂', exact=True).click()
    expect(student.get_by_text('评分 90 / 100', exact=True)).to_be_visible()
    passed('grade corrections append a review and preserve earlier grading history')
    student.set_viewport_size({'width':390,'height':844})
    assert student.evaluate('document.documentElement.scrollWidth <= innerWidth')
    expect(student.get_by_role('button', name='保存作业草稿', exact=True)).to_be_visible()
    passed('mobile classroom retains its actions without horizontal overflow')
    student.get_by_role('button', name='退出课堂', exact=True).click()
    expect(student.get_by_role('heading', name='进入课程课堂', exact=True)).to_be_visible()
    assert sc.request.get(URL+'/api/v1/classes').status == 401
    passed('logout revokes the real server session')
    tc.close(); sc.close(); browser.close()
assert not errors, errors
(ROOT/'outputs/COLORVERSE-course-test-report.json').write_text(json.dumps({'checks': checks, 'errors': errors}, ensure_ascii=False, indent=2), encoding='utf-8')
print(f'{len(checks)} course browser checks passed.')

